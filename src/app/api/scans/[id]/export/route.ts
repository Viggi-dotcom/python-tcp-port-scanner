import { NextRequest, NextResponse } from "next/server";
import { db } from "@/db";
import { scans, portResults } from "@/db/schema";
import { ensureDbSeeded } from "@/db/seed";
import { eq, asc } from "drizzle-orm";

function escapeCsvCell(val: string | number | null | undefined): string {
  const s = String(val ?? "");
  if (s.includes(",") || s.includes('"') || s.includes("\n")) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
}

export async function GET(
  request: NextRequest,
  context: { params: Promise<{ id: string }> }
) {
  try {
    await ensureDbSeeded();
    const { id } = await context.params;
    const scanId = Number(id);
    const format =
      request.nextUrl.searchParams.get("format")?.toLowerCase() || "txt";

    if (isNaN(scanId)) {
      return NextResponse.json({ error: "Invalid scan ID" }, { status: 400 });
    }

    const [scan] = await db.select().from(scans).where(eq(scans.id, scanId));
    if (!scan) {
      return NextResponse.json({ error: "Scan not found" }, { status: 404 });
    }

    const results = await db
      .select()
      .from(portResults)
      .where(eq(portResults.scanId, scanId))
      .orderBy(asc(portResults.port));

    const timestampStr = new Date(scan.createdAt).toISOString();
    const safeHost = scan.targetHost.replace(/[^a-zA-Z0-9._-]/g, "_");

    if (format === "csv") {
      const headers = [
        "scan_id",
        "timestamp_utc",
        "target_host",
        "target_label",
        "port",
        "protocol",
        "state",
        "service",
        "latency_ms",
        "risk_level",
        "banner",
        "raw_hex",
        "security_notes",
      ];
      const csvLines = [headers.join(",")];
      for (const r of results) {
        csvLines.push(
          [
            scan.id,
            timestampStr,
            scan.targetHost,
            scan.targetLabel,
            r.port,
            r.protocol,
            r.state,
            r.service,
            r.latencyMs ?? 1,
            r.riskLevel,
            r.banner || "",
            r.rawHex || "",
            r.securityNotes || "",
          ]
            .map(escapeCsvCell)
            .join(",")
        );
      }
      const csvContent = csvLines.join("\n") + "\n";

      return new NextResponse(csvContent, {
        status: 200,
        headers: {
          "Content-Type": "text/csv; charset=utf-8",
          "Content-Disposition": `attachment; filename="pyportscan_${safeHost}_scan${scan.id}.csv"`,
        },
      });
    }

    // Default: structured TXT report
    const divider = "=".repeat(92);
    const subDivider = "-".repeat(92);
    const txtLines = [
      divider,
      "PYPORTSCAN-LAB // NETWORK SECURITY TELEMETRY & TCP PORT SCAN REPORT",
      divider,
      `Scan Session ID  : #${scan.id}`,
      `Timestamp (UTC)  : ${timestampStr}`,
      `Target Host      : ${scan.targetHost} (${scan.targetLabel})`,
      `Port Range Spec  : ${scan.portRange} (${scan.totalPortsScanned} total ports probed)`,
      `Socket Config    : timeout=${scan.timeoutMs}ms | threads=${scan.threads} | banner_grab=${scan.grabBanner}`,
      `CLI Invocation   : ${scan.cliCommand}`,
      `Scan Duration    : ${scan.durationMs} ms`,
      `Summary Telemetry: ${scan.openCount} OPEN | ${scan.closedCount} CLOSED | ${scan.filteredCount} FILTERED`,
      subDivider,
      `${"PORT".padEnd(11)}${"STATE".padEnd(11)}${"SERVICE".padEnd(24)}${"RTT(ms)".padEnd(10)}${"RISK".padEnd(9)}BANNER / SERVICE HEADER`,
      subDivider,
    ];

    for (const r of results) {
      const portProto = `${r.port}/${r.protocol}`;
      const rtt = `${r.latencyMs ?? 1}ms`;
      const banner = r.banner || "-";
      txtLines.push(
        `${portProto.padEnd(11)}${r.state.toUpperCase().padEnd(11)}${r.service.padEnd(24)}${rtt.padEnd(10)}${r.riskLevel.toUpperCase().padEnd(9)}${banner}`
      );
      if (r.rawHex) {
        txtLines.push(`           └─ HEX PAYLOAD : ${r.rawHex}`);
      }
      if (r.securityNotes && r.state === "open") {
        txtLines.push(`           └─ SEC ADVISORY: ${r.securityNotes}`);
      }
    }

    txtLines.push(divider);
    txtLines.push(
      "End of Report // Generated by PyPortScan-Lab Python Socket Telemetry Utility"
    );
    const txtContent = txtLines.join("\n") + "\n";

    return new NextResponse(txtContent, {
      status: 200,
      headers: {
        "Content-Type": "text/plain; charset=utf-8",
        "Content-Disposition": `attachment; filename="pyportscan_${safeHost}_scan${scan.id}.txt"`,
      },
    });
  } catch (error: unknown) {
    console.error("GET /api/scans/[id]/export error:", error);
    return NextResponse.json(
      { error: "Failed to generate report export" },
      { status: 500 }
    );
  }
}
